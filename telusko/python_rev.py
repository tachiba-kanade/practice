#medium
class Menu:
    def __init__(self):
        self.numbers = []

    def add(self):
        count = int(input("How many numbers do you want to add? "))

        for i in range(count):
            num = int(input(f"Enter number {i + 1}: "))
            self.numbers.append(num)

        print("Numbers added successfully!")
        print("Current list:", self.numbers)

    def sort(self):
        self.numbers.sort()
        print("Sorted list:", self.numbers)

    def remove(self):
        num = int(input("Enter the number you want to remove: "))

        if num in self.numbers:
            self.numbers.remove(num)
            print(f"{num} removed successfully!")
        else:
            print(f"{num} is not in the list.")

        print("Current list:", self.numbers)

    def show_menu(self):
        while True:
            print("\n===== MENU =====")
            print("1. Add")
            print("2. Sort")
            print("3. Remove")
            print("4. Show ")
            print("5. Exit")

            choice = input("Enter your choice: ")

            if choice == "1":
                self.add()

            elif choice == "2":
                self.sort()

            elif choice == "3":
                self.remove()

            elif choice == "4":
                print("Current list:", self.numbers)

            elif choice == "5":
                print("byeeeeeeeeeeee")
                break

            else:
                print("Invalid.")


